// SUPERSEDED 2026-08-18 — DO NOT RE-RUN AGAINST PRODUCTION.
// The ladders below (and the migration this script writes) are the ORIGINAL
// 2026-06-17 brackets. They were replaced by
// supabase/migrations/2026-08-18_client_pref_area_budget_ranges.sql, which sets
// preferred_area to 50→5,000 (10 m² to 500, then 100 m²) and budget to
// 500,000→10,000,000 in uniform 50,000 steps, and which generates its ladders in
// SQL. Re-running this script and applying its output would REVERT that change.
// The canonical TS copy of the current ladders is `rangeLadder(...)` in
// src/data/seedModels.ts. Kept only as the record of the 2026-06-17 migration.
//
// Generates the bracket option ladders for the clients model's `budget` (SAR)
// and `preferred_area` (m²) range fields, and writes the migration that injects
// them into the live model schema. Option `value`s are NUMERIC strings so the
// stored {min,max} stays numeric (v_clients budget_min/max etc. depend on it).
//
//   node scripts/build-client-range-dropdowns.mjs
//
// Emits: supabase/migrations/2026-06-17_client_range_dropdowns.sql
// Prints: the TS option arrays (for seedModels.ts parity).

import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const __dirname = dirname(fileURLToPath(import.meta.url));
const repoRoot = join(__dirname, '..');

const fmt = (n) => n.toLocaleString('en-US');

function range(start, end, step) {
  const out = [];
  for (let v = start; v <= end; v += step) out.push(v);
  return out;
}

// Budget (SAR): 500K→1M in 50K, 1M→3M in 100K, 3M→10M in 1M (user-specified).
const budgetVals = [
  ...range(500000, 1000000, 50000),     // 500,000 … 1,000,000  (step 50K)
  ...range(1100000, 3000000, 100000),   // 1,100,000 … 3,000,000 (step 100K)
  ...range(4000000, 10000000, 1000000), // 4,000,000 … 10,000,000 (step 1M)
];

// Preferred area (m²): Standard 12-step ladder.
const areaVals = [100, 150, 200, 250, 300, 350, 400, 500, 750, 1000, 1500, 2000];

const opt = (prefix, v) => ({
  id: `${prefix}_${v}`,
  label_ar: fmt(v),
  label_en: fmt(v),
  value: String(v),
});

const budgetOpts = budgetVals.map((v) => opt('budget_opt', v));
const areaOpts = areaVals.map((v) => opt('area_opt', v));

const budgetJson = JSON.stringify(budgetOpts);
const areaJson = JSON.stringify(areaOpts);

const sql = `-- ============================================================================
-- Client range-dropdown options (budget + preferred_area).
--
-- Converts the clients model's two range fields from free-typed min/max
-- number inputs into DROPDOWN min/max pickers by attaching an options list
-- to each field. The render change lives in RangeField.tsx (renders two
-- <select>s when field.options is non-empty); this migration only adds the
-- option ladders to the live schema. Stored record values stay {min,max}
-- NUMERIC — option values are numeric strings — so v_clients budget_min/max
-- + preferred_area_min/max and every other range reader are unaffected.
--
-- Budget (ر.س): 500K→1M /50K, 1M→3M /100K, 3M→10M /1M  (${budgetVals.length} steps).
-- Preferred area (م²): 100→2000 standard ladder         (${areaVals.length} steps).
--
-- Generated by scripts/build-client-range-dropdowns.mjs — re-run to regenerate.
-- Idempotent: re-running overwrites the two fields' options with the same list.
-- ============================================================================

-- Backup the clients model row before mutating its schema.
CREATE TABLE IF NOT EXISTS public._backup_clients_model_20260617 AS
  SELECT * FROM public.models WHERE name = 'clients';

DO $$
DECLARE
  v_id uuid;
  v_schema jsonb;
  v_budget jsonb := '${budgetJson}'::jsonb;
  v_area   jsonb := '${areaJson}'::jsonb;
  s int;
  f int;
  v_name text;
BEGIN
  SELECT id, schema INTO v_id, v_schema FROM public.models WHERE name = 'clients';
  IF v_id IS NULL THEN RAISE EXCEPTION 'clients model not found'; END IF;

  FOR s IN 0 .. jsonb_array_length(v_schema->'sections') - 1 LOOP
    FOR f IN 0 .. jsonb_array_length(v_schema->'sections'->s->'fields') - 1 LOOP
      v_name := v_schema #>> ARRAY['sections', s::text, 'fields', f::text, 'name'];
      IF v_name = 'budget' THEN
        v_schema := jsonb_set(v_schema, ARRAY['sections', s::text, 'fields', f::text, 'options'], v_budget, true);
      ELSIF v_name = 'preferred_area' THEN
        v_schema := jsonb_set(v_schema, ARRAY['sections', s::text, 'fields', f::text, 'options'], v_area, true);
      END IF;
    END LOOP;
  END LOOP;

  -- Updating models.schema fires models_view_sync → v_clients is regenerated.
  UPDATE public.models SET schema = v_schema, updated_at = now() WHERE id = v_id;
  RAISE NOTICE 'clients budget/preferred_area options applied (% / % steps)',
    jsonb_array_length(v_budget), jsonb_array_length(v_area);
END $$;
`;

const outPath = join(repoRoot, 'supabase', 'migrations', '2026-06-17_client_range_dropdowns.sql');
writeFileSync(outPath, sql, 'utf8');

