/**
 * Regenerate the plan's worked scheduling examples FROM the engine, so the doc
 * can never drift from the code again (plan v2.1 correction 3).
 *
 *   node scripts/gen-scheduling-examples.mjs        # print markdown
 *   node scripts/gen-scheduling-examples.mjs --write # splice into the plan doc
 *
 * Runs the TypeScript engine through vite-node so there is exactly one
 * implementation — no re-derivation in JS.
 */
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync, mkdtempSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';

const RUNNER = `
import { planCampaign, DEFAULT_RULES } from './src/lib/marketingOS/scheduling/plan';
import { forecastCycles, creativeTotals } from './src/lib/marketingOS/scheduling/refresh';
import { DEFAULT_CALENDAR, weekdayOf } from './src/lib/marketingOS/scheduling/calendar';
import { DEFAULTS } from './src/lib/marketingOS/scheduling/types';

const CAL = { ...DEFAULT_CALENDAR };
const W='W', M1='M1', M2='M2', MM='MM', OPS='OPS';
const TEAM=[
  { userId:W,  roles:['writer'],            caps:{post:10,video:4,approvals:20}, leaves:[] },
  { userId:M1, roles:['montage'],           caps:{post:4,video:4,approvals:20},  leaves:[] },
  { userId:M2, roles:['montage'],           caps:{post:4,video:4,approvals:20},  leaves:[] },
  { userId:MM, roles:['marketing_manager'], caps:{approvals:20},                 leaves:[] },
  { userId:OPS,roles:['ops_supervisor'],    caps:{post:4,video:4,approvals:20},  leaves:[] },
];
const busy=(u,d,n)=>Array.from({length:n},(_,i)=>({userId:u,day:d,bucket:'post',weight:1,source:'task',refId:u+d+i}));
const BASE=[...busy(M1,'2026-10-06',2),...busy(M1,'2026-10-07',1),
  {userId:M2,day:'2026-10-06',bucket:'post',weight:1,source:'reservation',refId:'X'},
  {userId:M2,day:'2026-10-07',bucket:'post',weight:1,source:'reservation',refId:'X'}];
const TIGHT=[...BASE,...busy(M2,'2026-10-07',2)];
const snap=(ledger)=>({today:'2026-10-01',calendar:CAL,people:TEAM,ledger,hash:'gen'});

const P=(id,name,posts)=>({projectId:id,projectName:name,posts,videos:0});
const input={
  campaignId:null,kind:'organic',
  projects:[P('a','A',2),P('b','B',2),P('c','C',2)],
  platforms:['instagram'],rangeStart:'2026-10-11',rangeEnd:'2026-10-12',
  frequency:[{platform:'instagram',perDay:3,weekdays:null}],
  crossPost:false,publishBufferDays:1,
};

const out={};
for (const [name,ledger] of [['base',BASE],['tight',TIGHT]]) {
  const r=planCampaign(input,snap(ledger),DEFAULT_RULES);
  out[name]={
    feasible:r.feasible, proof:r.infeasibleProof, searchIncomplete:r.searchIncomplete,
    stats:r.searchStats,
    batches:r.batches.map(b=>({day:b.day,seq:b.sequence,items:b.itemKeys})),
    items:r.items.map(i=>({
      key:i.key,project:i.projectName,day:i.placements[0]?.day,slot:i.placements[0]?.slotIndex,
      grid:[i.placements[0]?.gridRow,i.placements[0]?.gridCol],
      ready:i.requiredReadyAt,prodStart:i.productionStart,
      stages:i.stages.map(s=>({step:s.stepKey,who:s.assigneeUserId,start:s.start,end:s.end,deadline:s.deadline})),
    })),
  };
}

const pol={...DEFAULTS.paid,bankedSpares:[]};
const cyc=forecastCycles({executionKey:'e',startsOn:'2026-10-01',endsOn:'2026-10-30',policy:pol},CAL);
out.paid={
  cycles:cyc.map(c=>({round:c.round,refreshOn:c.refreshOn,
    daysLeft:c.refreshOn?Math.round((Date.parse(\`2026-10-30\`)-Date.parse(c.refreshOn))/86400000)+1:null,
    readyBy:c.readyBy,prod:c.productionStartOn,decision:c.decisionDueOn,produced:c.produced,note:c.note})),
  totals:creativeTotals(cyc),
  totalsB:creativeTotals(forecastCycles({executionKey:'e',startsOn:'2026-10-01',endsOn:'2026-10-30',policy:{...pol,fifthPolicy:'B'}},CAL)),
};
out.dow = Object.fromEntries(['2026-09-30','2026-10-01','2026-10-03','2026-10-11','2026-10-12']
  .map(d=>[d,['Sun','Mon','Tue','Wed','Thu','Fri','Sat'][weekdayOf(d)]]));
console.log('@@JSON@@'+JSON.stringify(out));
`;

const dir = mkdtempSync(join(tmpdir(), 'wassel-sched-'));
const file = join(dir, 'gen.ts');
writeFileSync(file, RUNNER, 'utf8');
const raw = execFileSync('npx', ['--yes', 'vite-node', file], {
  cwd: process.cwd(), encoding: 'utf8', maxBuffer: 32 * 1024 * 1024, shell: process.platform === 'win32',
});
const json = JSON.parse(raw.slice(raw.indexOf('@@JSON@@') + 8).trim().split('\n')[0]);

const DOW = json.dow;
const day = (d) => `${d}${DOW[d] ? ` (${DOW[d]})` : ''}`;

const lines = [];
lines.push('### 22.1 Organic: three projects, publishing batches drive production', '');
lines.push('Generated by `node scripts/gen-scheduling-examples.mjs` from the engine itself.', '');
for (const [label, key] of [['Base ledger', 'base'], ['Tight variant (M2 also busy Oct 7)', 'tight']]) {
  const r = json[key];
  lines.push(`**${label}** — feasible: \`${r.feasible}\`, proof: \`${r.proof}\`, search complete: \`${!r.searchIncomplete}\` (${r.stats.expansions} expansions, ${r.stats.backtracks} backtracks)`, '');
  lines.push('| Item | Project | Publishes | Grid | Writing | Writing review | Design | Writer review | Final approval |');
  lines.push('|---|---|---|---|---|---|---|---|---|');
  for (const it of r.items) {
    const st = (k) => {
      const s = it.stages.find((x) => x.step === k);
      return s ? `${s.who} ${s.start}${s.start === s.end ? '' : `→${s.end}`}` : '—';
    };
    lines.push(`| ${it.key} | ${it.project} | ${it.day} #${it.slot} | r${it.grid[0]}c${it.grid[1]} | ${st('writing')} | ${st('writing_review')} | ${st('design')} | ${st('design_writer_review')} | ${st('design_review')} |`);
  }
  lines.push('');
}
lines.push('### 22.2 Paid: 30-day Meta campaign, weekly refresh, policy A', '');
lines.push('| Cycle | refresh_on | days left | ready_by | production start | decision due | produced |');
lines.push('|---|---|---|---|---|---|---|');
for (const c of json.paid.cycles) {
  lines.push(`| ${c.round === 0 ? 'launch' : c.round} | ${c.refreshOn ? day(c.refreshOn) : '—'} | ${c.daysLeft ?? '—'} | ${c.readyBy ?? '—'} | ${c.prod ?? '—'} | ${c.decision ?? '—'} | ${c.produced} |`);
}
const t = json.paid.totals;
lines.push('', `Policy A total: **${t.total}** creatives (${t.initial} launch + ${t.replacements} replacements + ${t.fifths} fifths) across ${t.cycles} kept refreshes. Policy B total: **${json.paid.totalsB.total}**.`, '');

const md = lines.join('\n');
if (process.argv.includes('--write')) {
  const path = 'docs/plans/campaign-scheduling-plan.md';
  const src = readFileSync(path, 'utf8');
  const start = src.indexOf('### 22.1');
  const end = src.indexOf('## 23. Failure cases');
  if (start < 0 || end < 0) throw new Error('anchors not found in the plan doc');
  writeFileSync(path, `${src.slice(0, start) + md}\n${src.slice(end)}`, 'utf8');
  console.log(`wrote ${path}`);
} else {
  console.log(md);
}
