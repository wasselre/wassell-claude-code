-- Public job-application experience — "مستشار مبيعات عقارية"
-- ============================================================================
-- A self-contained, dedicated feature (NOT a Builder model). Candidates arrive
-- from a paid ad on a PUBLIC page, answer a card-by-card form, and upload a CV +
-- a voice recording. The bytes land in a PRIVATE storage bucket; the answers land
-- in the dedicated `job_applications` table. An admin-only internal page reviews
-- them.
--
-- Storage / access posture (matches the CV/audio-are-PII requirement):
--   * bucket `job-applications` is PRIVATE with NO storage RLS policies, so it is
--     unreachable by anon/authenticated JWTs. The ONLY paths in are (a) a
--     one-shot signed UPLOAD url minted by the service-role API endpoint, and
--     (b) a short-lived signed DOWNLOAD url minted by the admin-gated API
--     endpoint. Public file URLs are never used.
--   * the public browser NEVER touches this table or bucket directly — every
--     write goes through the rate-limited `api/careers/*` service-role endpoints,
--     which validate MIME/size server-side (magic bytes, not the client's word).
--   * the `job_applications` table has RLS: admins read/update via their JWT
--     (the internal page uses the normal anon client + `wassell_is_admin`); the
--     public has no grant at all. Inserts are service-role only.
-- ============================================================================

-- ── 1. Private storage bucket ───────────────────────────────────────────────
-- No file_size_limit override here — the API endpoint enforces the real caps
-- (CV ≤ 10 MB, audio ≤ 25 MB). Deliberately NO storage.objects policies: the
-- bucket is reachable only via service-role signed urls.
INSERT INTO storage.buckets (id, name, public)
VALUES ('job-applications', 'job-applications', false)
ON CONFLICT (id) DO NOTHING;

-- ── 2. The application table ────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS public.job_applications (
  id                 uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  created_at         timestamptz NOT NULL DEFAULT now(),
  updated_at         timestamptz NOT NULL DEFAULT now(),

  -- Idempotency key generated by the browser and reused across retries so a
  -- double-click / accidental refresh cannot create a duplicate row.
  submission_id      uuid NOT NULL,

  -- Lifecycle status (canonical english keys; Arabic labels live in the UI).
  --   new | reviewing | interview | rejected | hired
  status             text NOT NULL DEFAULT 'new',

  -- Q1..Q10 answers ---------------------------------------------------------
  full_name          text NOT NULL,                 -- Q1
  phone              text NOT NULL,                  -- Q2 canonical KSA E.164 (+9665XXXXXXXX)
  phone_raw          text,                           -- as the applicant typed it
  current_situation  text,                           -- Q3  full_time|employed|student|job_seeker
  experience_level   text,                           -- Q4  none|less_than_1|1_to_3|more_than_3
  experience_results text,                           -- Q5  (only when experienced)
  can_commit         text,                           -- Q6  yes|no
  expected_salary    numeric,                         -- Q7a SAR
  expected_commission text,                          -- Q7b percentage (free text, e.g. "2%")
  additional_notes   text,                           -- Q10 (optional)

  -- Uploaded artefacts (paths inside the private `job-applications` bucket) ---
  cv_path            text,                           -- Q8 required
  cv_name            text,
  cv_mime            text,
  cv_size            bigint,
  audio_path         text,                           -- Q9 required
  audio_mime         text,
  audio_size         bigint,
  audio_duration_sec numeric,

  -- Attribution + debugging metadata ---------------------------------------
  source_url         text,
  utm                jsonb NOT NULL DEFAULT '{}'::jsonb,   -- utm_source/medium/campaign/term/content
  click_ids          jsonb NOT NULL DEFAULT '{}'::jsonb,   -- fbclid / gclid / ttclid / msclkid / ...
  client_meta        jsonb NOT NULL DEFAULT '{}'::jsonb,   -- ua, referrer, ip_hash, submitted_at

  CONSTRAINT job_applications_status_chk
    CHECK (status IN ('new','reviewing','interview','rejected','hired'))
);

-- One row per submission_id (idempotent retries collapse onto the same row).
CREATE UNIQUE INDEX IF NOT EXISTS job_applications_submission_id_uidx
  ON public.job_applications (submission_id);

CREATE INDEX IF NOT EXISTS job_applications_created_at_idx
  ON public.job_applications (created_at DESC);
CREATE INDEX IF NOT EXISTS job_applications_status_idx
  ON public.job_applications (status);
CREATE INDEX IF NOT EXISTS job_applications_phone_idx
  ON public.job_applications (phone);
CREATE INDEX IF NOT EXISTS job_applications_experience_idx
  ON public.job_applications (experience_level);

COMMENT ON TABLE public.job_applications IS
  'Public "مستشار مبيعات عقارية" job applications. Written only by the service-role api/careers/* endpoints; read/updated by admins via RLS. CV + audio live in the private job-applications bucket.';

-- ── 3. updated_at touch trigger ─────────────────────────────────────────────
CREATE OR REPLACE FUNCTION public.job_applications_touch_updated_at()
RETURNS trigger LANGUAGE plpgsql SET search_path = public, pg_catalog AS $fn$
BEGIN
  NEW.updated_at := now();
  RETURN NEW;
END;
$fn$;

DROP TRIGGER IF EXISTS job_applications_touch_updated_at ON public.job_applications;
CREATE TRIGGER job_applications_touch_updated_at
BEFORE UPDATE ON public.job_applications
FOR EACH ROW EXECUTE FUNCTION public.job_applications_touch_updated_at();

-- ── 4. RLS ──────────────────────────────────────────────────────────────────
ALTER TABLE public.job_applications ENABLE ROW LEVEL SECURITY;

-- Admins (the internal review page) can read every application through their JWT.
DROP POLICY IF EXISTS job_applications_admin_select ON public.job_applications;
CREATE POLICY job_applications_admin_select ON public.job_applications
  FOR SELECT TO authenticated
  USING (public.wassell_is_admin(auth.uid()));

-- Admins can update the status (and, if ever needed, correct fields).
DROP POLICY IF EXISTS job_applications_admin_update ON public.job_applications;
CREATE POLICY job_applications_admin_update ON public.job_applications
  FOR UPDATE TO authenticated
  USING (public.wassell_is_admin(auth.uid()))
  WITH CHECK (public.wassell_is_admin(auth.uid()));

-- Admins can delete (e.g. spam cleanup).
DROP POLICY IF EXISTS job_applications_admin_delete ON public.job_applications;
CREATE POLICY job_applications_admin_delete ON public.job_applications
  FOR DELETE TO authenticated
  USING (public.wassell_is_admin(auth.uid()));

-- No INSERT policy: inserts are service-role only (which bypasses RLS). The
-- public browser has zero direct access to this table.

-- ── 5. Rate-limiting helper (abuse control for the public endpoints) ─────────
-- A tiny counter keyed by a salted IP hash + a bucket kind + a time window.
-- Service-role only; the api/careers/* endpoints call it before doing work.
CREATE TABLE IF NOT EXISTS public.job_application_rate (
  ip_hash      text NOT NULL,
  kind         text NOT NULL,        -- 'upload' | 'submit'
  window_start timestamptz NOT NULL,
  hits         int NOT NULL DEFAULT 0,
  PRIMARY KEY (ip_hash, kind, window_start)
);

-- Returns TRUE when the caller is still under the limit (and records the hit),
-- FALSE when the limit is exceeded. Atomic upsert — safe under concurrency.
CREATE OR REPLACE FUNCTION public.job_application_rate_hit(
  p_ip_hash text, p_kind text, p_max int, p_window_seconds int
) RETURNS boolean
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, pg_catalog AS $fn$
DECLARE
  v_window_start timestamptz;
  v_hits int;
BEGIN
  -- Truncate now() to the window bucket so all hits in the same window collide.
  v_window_start := to_timestamp(floor(extract(epoch FROM now()) / p_window_seconds) * p_window_seconds);

  INSERT INTO public.job_application_rate (ip_hash, kind, window_start, hits)
  VALUES (COALESCE(NULLIF(p_ip_hash,''),'unknown'), p_kind, v_window_start, 1)
  ON CONFLICT (ip_hash, kind, window_start)
  DO UPDATE SET hits = public.job_application_rate.hits + 1
  RETURNING hits INTO v_hits;

  -- Opportunistic GC of old windows (cheap, bounded).
  DELETE FROM public.job_application_rate
   WHERE window_start < now() - interval '1 day';

  RETURN v_hits <= p_max;
END;
$fn$;

REVOKE ALL ON FUNCTION public.job_application_rate_hit(text, text, int, int) FROM public, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.job_application_rate_hit(text, text, int, int) TO service_role;
