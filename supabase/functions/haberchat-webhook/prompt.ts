export function buildSystemBlocks(args: {
  language: "ar" | "en";
  leadSummary: Preferences;
  contactName: string | null;
}): AnthropicContentBlock[] {
  const prefsDigest = Object.keys(args.leadSummary).length
    ? JSON.stringify(args.leadSummary)
    : "{}";
  const nameLine = args.contactName ? `اسم جهة الاتصال من واتساب: ${args.contactName}` : "";
  const languageHint =
    args.language === "en"
      ? "Detected language on last message: English. Reply in clear English, concise and warm."
      : "اللغة المكتشفة آخر رد: عربي. ردّ بلهجة نجدية بسيطة.";

  return [
    {
      type: "text",
      text: STATIC_SYSTEM,
      // @ts-expect-error the Anthropic SDK accepts cache_control on text blocks
      cache_control: { type: "ephemeral" },
    },
    {
      type: "text",
      text: `${languageHint}\n${nameLine}\nمعلومات العميل المعروفة حتى الآن (lead_summary): ${prefsDigest}`,
    },
  ];
}
