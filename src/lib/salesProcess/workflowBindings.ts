// Sales Process Studio ↔ Workflow binding resolution + drift detection.
//
// Workflows the Studio manages carry `metadata = { managed_by, sales_stage,
// activity_type, outcome, last_generated_hash }`. These helpers resolve which
// workflow implements a given activity/outcome (for the Studio's "linked
// workflow" + "Open in Workflow Builder") and flag drift (a Studio-generated
// workflow later hand-edited in the Builder). No automation is executed here.

import type { Workflow } from '@/types';
import type { SalesWorkflowBinding, SalesProcessConfig } from './types';
import { DEFAULT_SALES_PROCESS } from './config';

export function isStudioManaged(w: Workflow): boolean {
  return w.metadata?.managed_by === 'sales_process_studio';
}

/** All workflows whose metadata matches the (stage?, activity?, outcome?) ref. */
export function resolveBoundWorkflows(workflows: Workflow[], ref: SalesWorkflowBinding): Workflow[] {
  return workflows.filter((w) => {
    const m = w.metadata;
    if (!m) return false;
    if (ref.activity_type && m.activity_type !== ref.activity_type) return false;
    if (ref.sales_stage && m.sales_stage && m.sales_stage !== ref.sales_stage) return false;
    if (ref.outcome && m.outcome && m.outcome !== ref.outcome) return false;
    return true;
  });
}

export function resolveBoundWorkflow(workflows: Workflow[], ref: SalesWorkflowBinding): Workflow | undefined {
  return resolveBoundWorkflows(workflows, ref)[0];
}

export interface MissingBinding {
  activity_type: string;
  label_ar: string;
  label_en: string;
  stage?: string;
}

/** Config activities that have no Studio-managed workflow bound to them. */
export function findMissingWorkflowBindings(
  workflows: Workflow[],
  config: SalesProcessConfig = DEFAULT_SALES_PROCESS,
): MissingBinding[] {
  const missing: MissingBinding[] = [];
  for (const t of config.followup_types) {
    const bound = resolveBoundWorkflows(workflows, { activity_type: t.type });
    if (bound.length === 0) {
      missing.push({ activity_type: t.type, label_ar: t.label_ar, label_en: t.label_en, stage: t.stage });
    }
  }
  return missing;
}

// ── drift detection ──────────────────────────────────────────────────────────

/** Stable JSON of the executable shape (branches/conditions/actions), key-sorted. */
function stableStringify(value: unknown): string {
  if (value === null || typeof value !== 'object') return JSON.stringify(value);
  if (Array.isArray(value)) return `[${value.map(stableStringify).join(',')}]`;
  const obj = value as Record<string, unknown>;
  const keys = Object.keys(obj).sort();
  return `{${keys.map((k) => `${JSON.stringify(k)}:${stableStringify(obj[k])}`).join(',')}}`;
}

/** Small deterministic 32-bit hash (FNV-1a) of the workflow's executable shape. */
export function computeWorkflowShapeHash(w: Workflow): string {
  const shape = stableStringify({
    trigger_model_id: w.trigger_model_id,
    trigger_event: w.trigger_event,
    branches: w.branches ?? null,
    conditions: w.conditions ?? null,
    actions: w.actions ?? null,
  });
  let h = 0x811c9dc5;
  for (let i = 0; i < shape.length; i++) {
    h ^= shape.charCodeAt(i);
    h = Math.imul(h, 0x01000193);
  }
  return (h >>> 0).toString(16);
}

/**
 * True when a Studio-managed workflow's current shape no longer matches the hash
 * stamped when the Studio last generated it — i.e. it was edited by hand in the
 * Workflow Builder ("advanced"). The Studio must then refuse to silently
 * overwrite and offer "Open in Workflow Builder" instead.
 */
export function isWorkflowDrifted(w: Workflow): boolean {
  const stamped = w.metadata?.last_generated_hash;
  if (!stamped) return false; // never generated by the Studio, or unknown — not "drift"
  return computeWorkflowShapeHash(w) !== stamped;
}
