import { Readable } from 'node:stream';
import type Anthropic from '@anthropic-ai/sdk';
import { drive_v3, drive } from '@googleapis/drive';
import { OAuth2Client } from 'google-auth-library';
import type { GoogleDriveOAuth } from '../env.ts';

/**
 * `drive_upload` — copy a file from the Anthropic code-execution container
 * to Google Drive.
 *
 * Flow:
 *   1. Agent runs code_execution that writes a file (e.g. deck.pptx).
 *   2. The response includes a `bash_code_execution_output` block with a
 *      `file_id` from Anthropic's Files API.
 *   3. Agent calls drive_upload with that file_id + a filename.
 *   4. We download from Anthropic Files API → upload to Drive (using OAuth
 *      against the user's personal Google account) → return URL.
 *
 * The agent only sees Anthropic file IDs (start with `file_`). It never
 * sees Drive credentials or folder IDs — those live in the worker's env.
 *
 * Auth: OAuth refresh-token flow. Run `npm run oauth-init` once to capture
 * the refresh token; the OAuth2Client auto-refreshes access tokens after.
 */

export const DRIVE_UPLOAD_TOOL = {
  name: 'drive_upload',
  description:
    'Copy a file generated by code_execution to Google Drive and return its shareable URL. Pass the `file_id` you saw in the most recent bash_code_execution_output block, plus a human-readable filename. Do NOT call this until the file actually exists in the container — running this with a stale or invalid file_id will fail.',
  input_schema: {
    type: 'object' as const,
    properties: {
      file_id: {
        type: 'string',
        description:
          'The Anthropic Files API id (starts with "file_") for the file you want to upload. Find this in the bash_code_execution_output block of a prior code_execution response.',
      },
      filename: {
        type: 'string',
        description:
          'The filename to use in Google Drive. Should include the extension (e.g. "wassel-deck.pptx").',
      },
      mime_type: {
        type: 'string',
        description:
          'Optional MIME type override. Defaults are inferred from the extension: .pptx → application/vnd.openxmlformats-officedocument.presentationml.presentation, .pdf → application/pdf, .xlsx → application/vnd.openxmlformats-officedocument.spreadsheetml.sheet.',
      },
    },
    required: ['file_id', 'filename'],
  },
};

export interface DriveUploadInput {
  file_id: string;
  filename: string;
  mime_type?: string;
}

const MIME_BY_EXT: Record<string, string> = {
  pptx: 'application/vnd.openxmlformats-officedocument.presentationml.presentation',
  pdf: 'application/pdf',
  xlsx: 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet',
  docx: 'application/vnd.openxmlformats-officedocument.wordprocessingml.document',
  csv: 'text/csv',
  json: 'application/json',
  txt: 'text/plain',
  png: 'image/png',
  jpg: 'image/jpeg',
  jpeg: 'image/jpeg',
};

function inferMime(filename: string, override: string | undefined): string {
  if (override && override.trim() !== '') return override;
  const dot = filename.lastIndexOf('.');
  if (dot === -1) return 'application/octet-stream';
  const ext = filename.slice(dot + 1).toLowerCase();
  return MIME_BY_EXT[ext] ?? 'application/octet-stream';
}

export interface DriveUploadDeps {
  anthropic: Anthropic;
  oauth: GoogleDriveOAuth | null;
  parentFolderId: string | null;
}

export async function runDriveUpload(
  deps: DriveUploadDeps,
  input: DriveUploadInput,
): Promise<string> {
  if (!deps.oauth) {
    return 'Error: drive_upload is not configured. The worker is missing one of GOOGLE_OAUTH_CLIENT_ID, GOOGLE_OAUTH_CLIENT_SECRET, or GOOGLE_OAUTH_REFRESH_TOKEN. Tell the user the deck was built but cannot be uploaded; report the file_id in your final answer so they can retrieve it manually.';
  }

  // 1. Download the file from Anthropic Files API.
  let fileBuf: Buffer;
  let sourceMime: string | undefined;
  try {
    const meta = await deps.anthropic.beta.files.retrieveMetadata(input.file_id, {
      betas: ['files-api-2025-04-14'],
    });
    sourceMime = meta.mime_type ?? undefined;
    const downloadResp = await deps.anthropic.beta.files.download(input.file_id, {
      betas: ['files-api-2025-04-14'],
    });
    const ab = await downloadResp.arrayBuffer();
    fileBuf = Buffer.from(ab);
  } catch (err) {
    return `Error downloading file ${input.file_id} from Anthropic Files API: ${err instanceof Error ? err.message : String(err)}`;
  }

  // 2. Build the Drive client (with auto-refreshing OAuth token).
  const driveClient = buildDriveClient(deps.oauth);

  // 3. Upload.
  const mime = input.mime_type ?? inferMime(input.filename, sourceMime);
  let result;
  try {
    result = await driveClient.files.create({
      requestBody: {
        name: input.filename,
        ...(deps.parentFolderId ? { parents: [deps.parentFolderId] } : {}),
      },
      media: {
        mimeType: mime,
        body: Readable.from(fileBuf),
      },
      fields: 'id, name, webViewLink, webContentLink',
      supportsAllDrives: true,
    });
  } catch (err) {
    const msg = err instanceof Error ? err.message : String(err);
    if (msg.includes('invalid_grant')) {
      return `Error: Drive OAuth refresh failed (invalid_grant). The refresh token has been revoked or expired. Run \`npm run oauth-init\` again on the worker host to re-capture it.`;
    }
    if (msg.includes('File not found') || msg.includes('404')) {
      return `Error: Drive returned 404. Most likely cause: the GOOGLE_DRIVE_PARENT_FOLDER_ID points at a folder the OAuth user can't write to (or doesn't own). Pick a folder you own and update the env var.`;
    }
    return `Error uploading to Drive: ${msg}`;
  }

  const driveFile = result.data;
  return JSON.stringify(
    {
      ok: true,
      drive_file_id: driveFile.id,
      drive_url: driveFile.webViewLink,
      filename: driveFile.name,
      bytes: fileBuf.length,
      mime_type: mime,
    },
    null,
    2,
  );
}

let cachedClient: drive_v3.Drive | null = null;
let cachedClientFor: string | null = null;

function buildDriveClient(oauth: GoogleDriveOAuth): drive_v3.Drive {
  // Cache by client_id so we don't rebuild the OAuth client on every call.
  // The library handles access-token refresh internally — we just hand it
  // the refresh token once.
  if (cachedClient && cachedClientFor === oauth.clientId) return cachedClient;
  const oauthClient = new OAuth2Client({
    clientId: oauth.clientId,
    clientSecret: oauth.clientSecret,
  });
  oauthClient.setCredentials({ refresh_token: oauth.refreshToken });
  cachedClient = drive({ version: 'v3', auth: oauthClient });
  cachedClientFor = oauth.clientId;
  return cachedClient;
}
